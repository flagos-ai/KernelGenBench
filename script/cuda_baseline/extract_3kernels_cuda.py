"""
从Kaldi提取完整的CUDA源码用于3个kernels
"""

import re
from pathlib import Path


def extract_cuda_kernels():
    """
    提取copy_low_upp, copy_upp_low, add_mat的完整CUDA源码
    """
    
    kaldi_cu_kernels = Path("/share/project/zpy/k1_repo/src/cudamatrix/cu-kernels.cu")
    kaldi_matrixdim = Path("/share/project/zpy/k1_repo/src/cudamatrix/cu-matrixdim.h")
    
    # 读取源文件
    cu_content = kaldi_cu_kernels.read_text()
    
    # 提取MatrixDim定义
    matrixdim_content = kaldi_matrixdim.read_text()
    
    # 查找MatrixDim结构定义
    matrixdim_match = re.search(
        r'struct\s+MatrixDim\s*\{[^}]+\}',
        matrixdim_content,
        re.MULTILINE | re.DOTALL
    )
    
    matrixdim_def = matrixdim_match.group(0) if matrixdim_match else ""
    
    # 提取int32_cuda定义
    int32_cuda_match = re.search(r'typedef\s+.*\s+int32_cuda;', matrixdim_content)
    int32_cuda_def = int32_cuda_match.group(0) if int32_cuda_match else "typedef int int32_cuda;"
    
    # 构建完整的CUDA源码
    cuda_source = f"""
// Extracted from Kaldi cu-kernels.cu for copy_low_upp, copy_upp_low, add_mat
// Auto-generated by extract_3kernels_cuda.py

#include <cuda_runtime.h>

// Type definitions
{int32_cuda_def}

// MatrixDim structure
{matrixdim_def}

// ============================================================
// Kernel: copy_low_upp
// ============================================================
template<typename Real>
__global__
static void _copy_low_upp(Real* A, MatrixDim dimA) {{
  int i = blockIdx.x * blockDim.x + threadIdx.x;
  int j = blockIdx.y * blockDim.y + threadIdx.y;
  if (i <= j || i >= dimA.rows)
    return;
  int index_1 = i * dimA.stride + j;
  int index_2 = j * dimA.stride + i;
  A[index_2] = A[index_1];
}}

extern "C" {{
void cudaF_copy_low_upp(dim3 Gr, dim3 Bl, float* A, MatrixDim dimA) {{
  _copy_low_upp<<<Gr,Bl>>>(A, dimA);
}}

void cudaD_copy_low_upp(dim3 Gr, dim3 Bl, double* A, MatrixDim dimA) {{
  _copy_low_upp<<<Gr,Bl>>>(A, dimA);
}}
}}

// ============================================================
// Kernel: copy_upp_low
// ============================================================
template<typename Real>
__global__
static void _copy_upp_low(Real* A, MatrixDim dimA) {{
  int i = blockIdx.x * blockDim.x + threadIdx.x;
  int j = blockIdx.y * blockDim.y + threadIdx.y;
  if (j <= i || j >= dimA.rows)
    return;
  int index_1 = i * dimA.stride + j;
  int index_2 = j * dimA.stride + i;
  A[index_2] = A[index_1];
}}

extern "C" {{
void cudaF_copy_upp_low(dim3 Gr, dim3 Bl, float* A, MatrixDim dimA) {{
  _copy_upp_low<<<Gr,Bl>>>(A, dimA);
}}

void cudaD_copy_upp_low(dim3 Gr, dim3 Bl, double* A, MatrixDim dimA) {{
  _copy_upp_low<<<Gr,Bl>>>(A, dimA);
}}
}}

// ============================================================
// Kernel: add_mat
// ============================================================
template<typename Real>
__global__
static void _add_mat(Real alpha, const Real* src, Real* dst, MatrixDim d,
                     int src_stride) {{
  int32_cuda i = blockIdx.x * blockDim.x + threadIdx.x;  // column index
  int32_cuda j = blockIdx.y * blockDim.y + threadIdx.y;  // row index
  int32_cuda index = i + j * d.stride;
  int32_cuda index_src = i + j * src_stride;
  if (i < d.cols && j < d.rows)
    dst[index] = alpha * src[index_src] + dst[index];
}}

template<typename Real>
__global__
static void _add_mat_trans(Real alpha, const Real* src, Real* dst, MatrixDim d,
                           int src_stride) {{
  int32_cuda i = blockIdx.x * blockDim.x + threadIdx.x;
  int32_cuda j = blockIdx.y * blockDim.y + threadIdx.y;
  int32_cuda index = i + j * d.stride;
  int32_cuda index_src = j + i * src_stride;
  if (i < d.cols && j < d.rows)
    dst[index] = alpha * src[index_src] + dst[index];
}}

extern "C" {{
void cudaF_add_mat(dim3 Gr, dim3 Bl, float alpha, const float* src, float* dst,
                   MatrixDim d, int src_stride, int A_trans) {{
  if (A_trans) {{
    _add_mat_trans<<<Gr,Bl>>>(alpha, src, dst, d, src_stride);
  }} else {{
    _add_mat<<<Gr,Bl>>>(alpha, src, dst, d, src_stride);
  }}
}}

void cudaD_add_mat(dim3 Gr, dim3 Bl, double alpha, const double* src, double* dst,
                   MatrixDim d, int src_stride, int A_trans) {{
  if (A_trans) {{
    _add_mat_trans<<<Gr,Bl>>>(alpha, src, dst, d, src_stride);
  }} else {{
    _add_mat<<<Gr,Bl>>>(alpha, src, dst, d, src_stride);
  }}
}}
}}
"""
    
    return cuda_source


def main():
    print("="*60)
    print("Extracting CUDA source for 3 kernels")
    print("="*60)
    
    cuda_source = extract_cuda_kernels()
    
    # 保存到文件
    output_file = Path("/share/project/zpy/flagbench/cache/extracted_cuda/unified_3kernels.cu")
    output_file.parent.mkdir(parents=True, exist_ok=True)
    output_file.write_text(cuda_source)
    
    print(f"\n✓ Extracted CUDA source ({len(cuda_source)} bytes)")
    print(f"  Output: {output_file}")
    print(f"\nKernels included:")
    print("  - copy_low_upp (float/double)")
    print("  - copy_upp_low (float/double)")
    print("  - add_mat (float/double, with transpose support)")
    
    print("\n" + "="*60)
    print("✓ Extraction complete!")
    print("="*60)


if __name__ == "__main__":
    main()
